// Write lib/article-review-index.ts from the full article data:
// `pnpm review:index`. `--check` fails when the committed file is stale.
import { build } from 'esbuild';
import { spawnSync } from 'node:child_process';
import { readFile, writeFile } from 'node:fs/promises';

const target = 'lib/article-review-index.ts';
const checkOnly = process.argv.includes('--check');
const result = await build({
  entryPoints: ['lib/article-review-source.ts'],
  bundle: true,
  write: false,
  platform: 'node',
  format: 'esm',
});
const { buildArticleReviewIndex } = await import(
  `data:text/javascript;base64,${Buffer.from(result.outputFiles[0].text).toString('base64')}`
);
const { reviews, gameContexts, categories, reportableGames } =
  buildArticleReviewIndex();
const source = `// Generated by scripts/generate-article-review-index.mjs. Do not edit.
import type { ArticleReview } from './article-review-source';

export const articleReviews: Record<string, Omit<ArticleReview, 'path'>> =
  ${JSON.stringify(reviews)};

export const gameArticleContexts: Record<string, string> = ${JSON.stringify(gameContexts)};

export const gameArticleCategories: Record<string, string> = ${JSON.stringify(categories)};

export const reportableGames: readonly string[] = ${JSON.stringify(reportableGames)};
`;
// The check copy keeps a .ts extension so oxfmt formats it the same way.
const out = checkOnly ? 'lib/article-review-index.check.ts' : target;
await writeFile(out, source);
spawnSync('npx', ['oxfmt', out], { stdio: 'ignore' });
if (checkOnly) {
  const [current, fresh] = await Promise.all([
    readFile(target, 'utf8').catch(() => ''),
    readFile(out, 'utf8'),
  ]);
  spawnSync('rm', ['-f', out]);
  if (current !== fresh) {
    console.error(`${target} is out of date. Run: pnpm review:index`);
    process.exit(1);
  }
  console.log(`${target} is up to date.`);
} else {
  console.log(
    `Wrote ${target}: ${Object.keys(reviews).length} articles, ${Object.keys(gameContexts).length} contexts.`,
  );
}
