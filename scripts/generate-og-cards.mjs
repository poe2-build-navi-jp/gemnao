// Render per-page social preview cards: `pnpm og:cards`.
// Only new or changed cards are re-rendered; the manifest records a hash of
// each card's text so metadata can add `?v=` and X refreshes its cache.
// `--check` only reports cards that are missing or out of date.
import { build } from 'esbuild';
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync } from 'node:fs';
import { readFile, rm, writeFile } from 'node:fs/promises';

const manifestPath = 'lib/og-image-manifest.ts';
const checkOnly = process.argv.includes('--check');

const result = await build({
  entryPoints: ['lib/og-cards.ts'],
  bundle: true,
  write: false,
  platform: 'node',
  format: 'esm',
});
const { ogCardSpecs } = await import(
  `data:text/javascript;base64,${Buffer.from(result.outputFiles[0].text).toString('base64')}`
);
const specs = ogCardSpecs();
const imageFile = (path) => `public/images/og${path}.png`;
const hash = (spec) =>
  createHash('sha256').update(JSON.stringify(spec)).digest('hex').slice(0, 8);

const previous = existsSync(manifestPath)
  ? JSON.parse(
      (await readFile(manifestPath, 'utf8')).match(/= (\{[\s\S]*\});/)?.[1] ||
        '{}',
    )
  : {};
const next = Object.fromEntries(specs.map((spec) => [spec.path, hash(spec)]));
const stale = specs.filter(
  (spec) =>
    previous[spec.path] !== next[spec.path] ||
    !existsSync(imageFile(spec.path)),
);
const removed = Object.keys(previous).filter((path) => !(path in next));

if (checkOnly) {
  if (stale.length || removed.length)
    console.warn(
      `OG cards out of date (${stale.length} to render, ${removed.length} to remove). Run \`pnpm og:cards\`; until then those pages use the default image.`,
    );
  else console.log(`OG cards up to date: ${specs.length} pages`);
} else {
  if (stale.length) {
    const render = spawnSync('python3', ['scripts/render-og-cards.py'], {
      input: JSON.stringify(stale),
      encoding: 'utf8',
      maxBuffer: 1024 * 1024,
    });
    if (render.stdout) console.log(render.stdout.trim());
    if (render.stderr) console.error(render.stderr.trim());
    if (render.status !== 0) throw new Error('OG card rendering failed');
  }
  for (const path of removed) await rm(imageFile(path), { force: true });
  const sorted = Object.fromEntries(
    Object.entries(next).sort(([a], [b]) => a.localeCompare(b)),
  );
  await writeFile(
    manifestPath,
    `// Generated by scripts/generate-og-cards.mjs. Do not edit by hand.\n// Page path -> hash of the card text (used as a cache-busting query).\nexport const ogImageManifest: Record<string, string> = ${JSON.stringify(sorted, null, 2)};\n`,
  );
  console.log(
    `OG cards: ${specs.length} pages (${stale.length} rendered, ${removed.length} removed)`,
  );
}
